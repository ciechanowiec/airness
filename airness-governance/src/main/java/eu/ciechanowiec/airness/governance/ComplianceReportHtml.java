package eu.ciechanowiec.airness.governance;

import lombok.experimental.UtilityClass;

/**
 * Renders one self-contained, offline-readable compliance report.
 */
@UtilityClass
public final class ComplianceReportHtml {

    /**
     * Renders the screen and print document from evaluated evidence.
     *
     * @param report the complete report
     * @return HTML with inline resources and safely encoded downloads
     */
    public static String render(ComplianceReport report) {
        ReportSections sections = new ReportSections(report);
        return "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
            + "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
            + "<title>Open Source Software Compliance Report - " + ReportMarkup.escape(report.project())
            + "</title><style>" + ReportAssets.styles() + "</style></head><body>"
            + "<div id=\"header\"><h1>Open Source Software Compliance Report</h1>"
            + ReportOutline.contents() + "</div><main id=\"content\">" + sections.opening()
            + ReportOutline.section("Executive summary", sections.summary())
            + ReportOutline.section("License policy", sections.policy())
            + ReportOutline.section("Copyleft and policy review", ReportTables.review(report.inventory()))
            + ReportOutline.section("Known vulnerabilities", ReportTables.advisories(report.inventory().advisories()))
            + ReportOutline.section("Package inventory", ReportTables.inventory(report))
            + ReportOutline.section("Third-party notices", sections.notices())
            + ReportOutline.section("Provenance and reproduction", sections.provenance())
            + "</main><footer id=\"footer\">Generated by Airness for " + ReportMarkup.escape(report.project())
            + " at " + ReportMarkup.escape(report.source().commit()) + ".</footer>"
            + "<script type=\"application/json\" id=\"report-data\">" + report.evidence().downloads()
            + "</script><script>" + ReportAssets.script() + "</script></body></html>\n";
    }
}
